from os.path import join
import glob
import sys
Import("env")

# Install yaml if missing
try:
    import yaml
except ImportError:
    env.Execute("$PYTHONEXE -m pip install pyyaml")
    import yaml

platform = env.PioPlatform()
PROJ_SRC = env["PROJECT_SRC_DIR"]
PROJECT_DIR = env["PROJECT_DIR"]
CONFIG_FILES = glob.glob(join(PROJ_SRC, '*/param.yaml'), recursive=True)
outfilename =  PROJECT_DIR + "/Parameters.md"

print("==============================================")
print("madflight documentation generator")
print(f"Generating {outfilename}")

#load all config files into param
param = {}
for filename in CONFIG_FILES:
  print(f"  from {filename.removeprefix(PROJ_SRC)}")
  with open(filename) as stream:
    y = yaml.safe_load(stream)
    since = ""
    for k in y['param']:
      #add param
      param[k] = y['param'][k]
      #create comment if not exist 
      if not 'comment' in param[k]:
        param[k]['comment'] = ""
      #create since if not exist 
      if 'since' in param[k]:
        since = param[k]['since']
      param[k]['since'] = since
      #create options if not exist 
      if not 'options' in param[k]:
        param[k]['options'] = {}
      #create default if not exist 
      if not 'default' in param[k]:
        param[k]['default'] = ""

#write doc file
param = dict(sorted(param.items()))
with open(outfilename, "w") as f:
  f.write(f"<!--- DO NOT EDIT - GENERATED BY extras/scripts/doc_generator.py -->\n")
  f.write("\n")  

  f.write(f"# madflight Config Parameters\n")
  f.write(f"|Parameter|Description|Default|Options|\n")
  f.write(f"|-|-|-|-|\n")
  for k in param:
    p = param[k]

    options = "<br>".join(p['options'])

    descr = p['comment']
    if p['since']:
      descr += f"<br>_since {p['since']}_"

    f.write(f"|`{k}`|{descr}|{p['default']}|{options}|\n")


print("==============================================")

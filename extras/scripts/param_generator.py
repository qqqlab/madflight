g_enum = {}

def mf_options(p):
  global g_enum
  if 'options' in p:
    return "mf_" + ",mf_".join(p['options'])
  elif 'enum' in p:
    return "mf_" + ",mf_".join(g_enum[ p['enum'] ]['options'])
  else:
    return ""
  

def generate_config(outfilename, y):
  global g_enum
  with open(outfilename, "w") as f:
    param = y['param'] #required

    f.write(f"// DO NOT EDIT - GENERATED BY extras/scripts/param_generator.py\n")
    f.write("\n")
    f.write("#pragma once\n")
    f.write("\n")
    f.write("#include <stdint.h>\n")
    f.write("\n")

    # dump global enums
    enum = y.get('enum') #optional
    if(enum):
      g_enum = enum
      f.write("// Global enums\n")
      for k in enum:
        e = enum[k]
        f.write(f"{e['datatype']} {{ {mf_options(e)} }};\n")
      f.write("\n")

    # start namespace
    f.write("namespace Cfg {\n")

    # dump parameter count
    f.write(f"  const uint16_t param_cnt = {len(param)}; //number of parameters\n")
    f.write("\n")

    # dump local enums
    f.write("  //enums for madflight library parameters (prefixed with 'mf_' to prevent macro expansion of global #defines like ADC or ICM45686)\n")
    for k in param:
      p = param[k]
      if p['type'] == 'e':
        if not 'enum' in p:
          #local enum
          f.write(f"  enum class {k}_enum : uint32_t {{ {mf_options(p)} }};\n")
          param[k]['datatype'] = f"Cfg::{k}_enum" #change datatype to enum
          param[k]['default'] =  f"Cfg::{k}_enum::mf_" + str(param[k]['default']) #expand default to enum key
        else:
          #global enum
          param[k]['datatype'] = f"{p['enum']}" #change datatype to enum
          param[k]['default'] =  f"{p['enum']}::mf_" + str(param[k]['default']) #expand default to enum key
    f.write("\n")

    # dump parameter lookup table
    f.write("  //list of parameters\n")
    f.write("  struct param_list_t {\n")
    f.write("    const char* name;\n")
    f.write("    const float defval;\n")
    f.write("    const char type;\n")
    f.write("    const char* options;\n")
    f.write("  };\n")
    f.write("  const param_list_t param_list[] = {\n")
    for k in param:
      p = param[k]
      f.write(f"    {{ \"{k}\", (float){p['default']}, '{p['type']}', \"{mf_options(p)}\" }},\n")
    f.write("  }; //const param_list_t param_list[]\n")

    # close namespace
    f.write("}; //namespace Cfg\n")
    f.write("\n")

    # dump parameters
    f.write("//all parameters with defaults\n")
    f.write("struct CfgParam {\n")
    for k in param:
      p = param[k]
      if 'since' in p:
        f.write(f"  // {p['since']}\n")
      comment = ""
      if 'comment' in p: 
        comment = " /* " + p['comment'] + " */"
      f.write(f"  {p['datatype']} {k} = {p['default']};{comment}\n")
    f.write("}; //struct CfgParam\n")
    

platform = env.PioPlatform()
PROJ_SRC = env["PROJECT_SRC_DIR"]
CONFIG_FILES = glob.glob(join(PROJ_SRC, '*/param.yaml'), recursive=True)

print("==============================================")
print("madflight parameter generator")
#print("PROJ_SRC:", PROJ_SRC)

for filename in CONFIG_FILES:
  print(f"Generating {filename.removeprefix(PROJ_SRC)}.h from {filename.removeprefix(PROJ_SRC)}")
  with open(filename) as stream:
    y = yaml.safe_load(stream)
    #print(y)
    generate_config(filename + ".h", y)

print("==============================================")
